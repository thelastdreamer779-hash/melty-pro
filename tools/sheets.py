#!/usr/bin/env python3
"""Preflight the design sheets and generate C# from them.

  python3 tools/sheets.py preflight   # list unfilled cells, broken references, unverified rows
  python3 tools/sheets.py gen         # preflight, then write src/TurnipDash/Generated/Sheets.g.cs

The sheets in design/sheets are the source of truth: change a sheet, then regenerate.
"""
import json, math, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEETS = os.path.join(ROOT, "design", "sheets")
OUT = os.path.join(ROOT, "src", "TurnipDash", "Generated", "Sheets.g.cs")

# column -> sheet it must point at ("none" allowed where listed)
REFS = {
    ("games", "missingText"): ("ui", False),
    ("content", "game"): ("games", False),
    ("content", "atlas"): ("content", True),
    ("content", "usedBy"): ("stages", False),
    ("gd_objects", "frame"): ("content", False),
    ("stages", "next"): ("stages", True),
    ("stages", "music"): ("content", True),
    ("stages", "avatar"): ("content", True),
    ("stages", "enterText"): ("ui", False),
    ("hooks", "usedBy"): ("stages", False),
}
VERIFIED_OK = {"build", "melty-game_info", "in-game"}


def load():
    sheets = {}
    for f in sorted(os.listdir(SHEETS)):
        if f.endswith(".json"):
            d = json.load(open(os.path.join(SHEETS, f)))
            sheets[d["sheet"]] = d
    return sheets


def preflight(sheets):
    problems, unverified, cells = [], [], 0
    ids = {name: {r["id"] for r in s["rows"]} for name, s in sheets.items()}
    for name, s in sheets.items():
        seen = set()
        for r in s["rows"]:
            if r["id"] in seen:
                problems.append(f"{name}.{r['id']}: duplicate id")
            seen.add(r["id"])
            for c in s["columns"]:
                cells += 1
                v = r.get(c)
                if v is None or v == "":
                    problems.append(f"{name}.{r['id']}.{c}: unfilled")
                    continue
                ref = REFS.get((name, c))
                if ref:
                    target, none_ok = ref
                    if not (none_ok and v == "none") and v not in ids[target]:
                        problems.append(f"{name}.{r['id']}.{c}: '{v}' is not a row of {target}")
            extra = set(r) - set(s["columns"])
            if extra:
                problems.append(f"{name}.{r['id']}: cells outside the columns {sorted(extra)}")
            if "verified" in s["columns"] and r.get("verified") not in VERIFIED_OK:
                unverified.append(f"{name}.{r['id']} ({r.get('verified')})")
    # cross-sheet rules
    rule = sheets["climb_rules"]["rows"][0]
    route = sheets["climb_route"]["rows"]
    for a, b in zip(route, route[1:]):
        if math.hypot(b["x"] - a["x"], b["y"] - a["y"]) > rule["reach"]:
            problems.append(f"climb_route.{b['id']}: out of reach of {a['id']}")
    if route[-1]["y"] < rule["summitY"]:
        problems.append("climb_route: last hold is below climb_rules.summitY")
    for st in sheets["stages"]["rows"]:
        if st["kind"] == "climb" and st["avatar"] == "none":
            problems.append(f"stages.{st['id']}: a climb needs an avatar")
    gdids = [r["gdObjectId"] for r in sheets["gd_objects"]["rows"]]
    if len(gdids) != len(set(gdids)):
        problems.append("gd_objects: a gdObjectId appears twice")
    return problems, unverified, cells


def cs(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v) + "f"
    return json.dumps(v)


def pascal(s):
    return s[:1].upper() + s[1:]


def gen(sheets):
    lines = ["// <auto-generated> from design/sheets by tools/sheets.py. Edit the sheets, not this file. </auto-generated>",
             "namespace TurnipDash.Generated", "{"]
    for name, s in sheets.items():
        tname = "".join(pascal(p) for p in name.split("_")) + "Row"
        cols = s["columns"]
        sample = s["rows"][0]
        def ctype(c):
            v = sample[c]
            return "bool" if isinstance(v, bool) else "int" if isinstance(v, int) else "float" if isinstance(v, float) else "string"
        # a column is float if any row holds a float there
        types = {}
        for c in cols:
            vals = [r[c] for r in s["rows"]]
            if all(isinstance(v, bool) for v in vals): types[c] = "bool"
            elif all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in vals):
                types[c] = "float" if any(isinstance(v, float) for v in vals) else "int"
            else: types[c] = "string"
        lines.append(f"    /// <summary>{s['about']}</summary>")
        lines.append(f"    public sealed class {tname}")
        lines.append("    {")
        for c in cols:
            lines.append(f"        public readonly {types[c]} {pascal(c)};")
        args = ", ".join(f"{types[c]} {c}" for c in cols)
        lines.append(f"        public {tname}({args})")
        lines.append("        {")
        for c in cols:
            lines.append(f"            {pascal(c)} = {c};")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
    lines.append("    public static class Sheets")
    lines.append("    {")
    for name, s in sheets.items():
        tname = "".join(pascal(p) for p in name.split("_")) + "Row"
        field = "".join(pascal(p) for p in name.split("_"))
        lines.append(f"        public static readonly {tname}[] {field} =")
        lines.append("        {")
        for r in s["rows"]:
            vals = []
            for c in s["columns"]:
                v = r[c]
                if isinstance(v, int) and not isinstance(v, bool) and any(isinstance(x[c], float) for x in s["rows"]):
                    v = float(v)
                vals.append(cs(v))
            lines.append(f"            new {tname}({', '.join(vals)}),")
        lines.append("        };")
        lines.append("")
    lines.append("    }")
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines) + "\n")


def main():
    sheets = load()
    problems, unverified, cells = preflight(sheets)
    rows = sum(len(s["rows"]) for s in sheets.values())
    print(f"preflight: {len(sheets)} sheets, {rows} rows, {cells} cells")
    for p in problems:
        print("  FAIL", p)
    print(f"  {len(unverified)} rows not yet verified in the running game")
    if "-v" in sys.argv:
        for u in unverified:
            print("   ", u)
    if problems:
        print("preflight: NOT clean")
        sys.exit(1)
    print("preflight: clean (every cell filled, every reference resolves)")
    if len(sys.argv) > 1 and sys.argv[1] == "gen":
        gen(sheets)
        print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
