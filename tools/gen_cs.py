#!/usr/bin/env python3
"""Generate src/TurnipDash/Sheets.g.cs: one C# record instance per sheet row, built from that row's columns."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
S = {n: json.load(open(os.path.join(ROOT, 'sheets', n + '.json'))) for n in ['games', 'content', 'rooms', 'modes', 'entities']}
def cs(v):
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return f'{float(v)}f'
    if isinstance(v, list): return 'new[] { ' + ', '.join(cs(x) for x in v) + ' }'
    return json.dumps(v)
def ident(s): return ''.join(p[:1].upper() + p[1:] for p in s.replace('-', '_').split('_'))
out = ['// <auto-generated> from sheets/*.json by tools/gen_cs.py. Edit the sheets, not this file. </auto-generated>',
       'namespace Celeste.Mod.TurnipDash;', '',
       'public sealed record GameRow(string Id, string Name, string SteamAppId, string InstallDirName, string ContentRoot);',
       'public sealed record ContentRow(string Id, string Game, string Kind, string[] Lookup, string Pick, string WhenMissing);',
       'public sealed record RoomRow(string Id, string Music, string StartMode);',
       'public sealed record ModeRow(string Id, string State, float RunSpeed, float Gravity, float JumpSpeed, float LiftAccel, float MaxFall, float MaxRise, float Reach, float Pull, float GripRadius, bool DiesOnWallHit, float SpinDegPerSec);',
       'public sealed record EntityRow(string Id, string EverestName, string Art, float Width, float Height);', '',
       'public static class Sheets {']
for r in S['games']['rows']:
    if r['role'] == 'primary': continue
    out.append(f'    public static readonly GameRow Game{ident(r["id"])} = new({cs(r["id"])}, {cs(r["name"])}, {cs(r["steamAppId"])}, {cs(r["installDirName"])}, {cs(r["contentRoot"])});')
for r in S['content']['rows']:
    out.append(f'    public static readonly ContentRow {ident(r["id"])} = new({cs(r["id"])}, {cs(r["game"])}, {cs(r["kind"])}, {cs(r["lookup"])}, {cs(r["pick"])}, {cs(r["whenMissing"])});')
for r in S['rooms']['rows']:
    out.append(f'    public static readonly RoomRow Room{ident(r["id"])} = new({cs(r["id"])}, {cs(r["music"])}, {cs(r["startMode"])});')
for r in S['modes']['rows']:
    out.append(f'    public static readonly ModeRow Mode{ident(r["id"])} = new({cs(r["id"])}, {cs(r["state"])}, {cs(r["runSpeed"])}, {cs(r["gravity"])}, {cs(r["jumpSpeed"])}, {cs(r["liftAccel"])}, {cs(r["maxFall"])}, {cs(r["maxRise"])}, {cs(r["reach"])}, {cs(r["pull"])}, {cs(r["gripRadius"])}, {cs(r["diesOnWallHit"])}, {cs(r["spinDegPerSec"])});')
for r in S['entities']['rows']:
    if r['class'] == 'vanilla': continue
    out.append(f'    public static readonly EntityRow Entity{r["id"]} = new({cs(r["id"])}, {cs(r["everestName"])}, {cs(r["art"])}, {cs(r["width"])}, {cs(r["height"])});')
def lst(name, typ, prefix, rows, f=lambda r: True):
    out.append(f'    public static readonly {typ}[] {name} = {{ ' + ', '.join(prefix + ident(r['id']) if prefix != 'Entity' else prefix + r['id'] for r in rows if f(r)) + ' };')
lst('Content', 'ContentRow', '', S['content']['rows'])
lst('Rooms', 'RoomRow', 'Room', S['rooms']['rows'])
lst('Modes', 'ModeRow', 'Mode', S['modes']['rows'])
lst('Games', 'GameRow', 'Game', S['games']['rows'], lambda r: r['role'] != 'primary')
out.append('}')
p = os.path.join(ROOT, 'src', 'TurnipDash', 'Sheets.g.cs'); os.makedirs(os.path.dirname(p), exist_ok=True)
open(p, 'w').write('\n'.join(out) + '\n'); print('wrote', p, len(out), 'lines')
